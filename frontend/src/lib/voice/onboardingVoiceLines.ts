/**
 * Gets pre-generated audio file path if available.
 */
export function getPreGeneratedAudioPath(lang: string, gender: 'girl' | 'boy', lineId: string): string {
  const cleanLang = lang.split('-')[0].toLowerCase();
  const cleanGender = gender === 'boy' ? 'boy' : 'girl';
  return `/audio/${cleanLang}/${cleanGender}/${lineId}.mp3`;
}
